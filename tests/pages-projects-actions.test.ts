import { beforeEach, describe, expect, it, vi } from 'vitest';

const mocks = vi.hoisted(() => ({
  requireAdmin: vi.fn(),
  txPageUpdateMany: vi.fn(),
  txProjectUpdateMany: vi.fn(),
  pageCreate: vi.fn(),
  auditCreate: vi.fn(),
  projectFindFirst: vi.fn(),
  projectCreate: vi.fn(),
  mediaCount: vi.fn(),
  productCount: vi.fn(),
}));
vi.mock('@/lib/auth', () => ({ requireAdmin: mocks.requireAdmin }));
vi.mock('@/lib/db', () => ({
  db: {
    $transaction: vi.fn(async (callback: (tx: unknown) => unknown) =>
      callback({
        pageContent: {
          updateMany: mocks.txPageUpdateMany,
          findUniqueOrThrow: vi.fn(),
          create: mocks.pageCreate,
        },
        project: {
          updateMany: mocks.txProjectUpdateMany,
          create: mocks.projectCreate,
          update: vi.fn(),
        },
        auditLog: { create: mocks.auditCreate },
      }),
    ),
    pageContent: { findFirst: vi.fn(), findUnique: vi.fn() },
    project: { findFirst: mocks.projectFindFirst, updateMany: mocks.txProjectUpdateMany },
    media: { count: mocks.mediaCount },
    product: { count: mocks.productCount },
  },
}));
vi.mock('next/cache', () => ({ revalidatePath: vi.fn() }));
import { savePage } from '@/app/admin/(protected)/pages/actions';
import { approveProject, saveProject } from '@/app/admin/(protected)/projects/actions';

describe('page and project publication boundaries', () => {
  beforeEach(() => {
    vi.clearAllMocks();
    mocks.requireAdmin.mockResolvedValue({ id: 'admin-1', role: 'ADMIN' });
  });
  it('requires server administrator authorization before reading or changing a page', async () => {
    mocks.requireAdmin.mockRejectedValueOnce(new Error('Administrator access required.'));
    await expect(savePage(new FormData())).rejects.toThrow('Administrator access required');
    expect(mocks.pageCreate).not.toHaveBeenCalled();
    expect(mocks.txPageUpdateMany).not.toHaveBeenCalled();
  });
  it('requires server administrator authorization before project lookups', async () => {
    mocks.requireAdmin.mockRejectedValueOnce(new Error('Administrator access required.'));
    await expect(approveProject('project-1', new Date().toISOString())).rejects.toThrow(
      'Administrator access required',
    );
    expect(mocks.projectFindFirst).not.toHaveBeenCalled();
  });
  it('keeps a page private when an optimistic version check loses a race', async () => {
    mocks.txPageUpdateMany.mockResolvedValueOnce({ count: 0 });
    const form = new FormData();
    form.set('id', 'page-1');
    form.set('version', '4');
    form.set('title', 'Company story');
    form.set('slug', 'company-story');
    form.set('sectionCount', '1');
    form.set('sectionHeading0', 'Our story');
    form.set('sectionBody0', 'A concise account of the company.');
    const result = await savePage(form);
    expect(result).toMatchObject({
      ok: false,
      message: expect.stringContaining('changed in another session'),
    });
    expect(mocks.auditCreate).not.toHaveBeenCalled();
  });
  it('refuses to approve a project if its draft changed after the review loaded', async () => {
    mocks.projectFindFirst.mockResolvedValueOnce({
      slug: 'qa-project',
      body: {
        challenge: 'A verified challenge narrative.',
        solution: 'A verified solution narrative.',
      },
      clientName: null,
      clientPermissionAt: null,
      images: [],
      title: 'QA project',
    });
    mocks.txProjectUpdateMany.mockResolvedValueOnce({ count: 0 });
    const result = await approveProject('project-1', new Date().toISOString());
    expect(result).toMatchObject({
      ok: false,
      message: expect.stringContaining('changed before approval'),
    });
    expect(mocks.auditCreate).not.toHaveBeenCalled();
  });
  it('accepts UUID media identifiers generated by the media library', async () => {
    const imageId = '123e4567-e89b-12d3-a456-426614174000';
    mocks.mediaCount.mockResolvedValueOnce(1);
    mocks.productCount.mockResolvedValueOnce(0);
    mocks.projectCreate.mockResolvedValueOnce({ id: 'project-created' });
    const form = new FormData();
    form.set('title', 'Verified project story');
    form.set('slug', 'verified-project-story');
    form.set('challenge', 'A detailed verified challenge description from the completed work.');
    form.set('solution', 'A detailed verified solution description from the completed work.');
    form.set('clientPermission', 'no');
    form.set('featured', 'no');
    form.set('imageIds', imageId);
    const result = await saveProject(form);
    expect(result).toMatchObject({ ok: true, id: 'project-created' });
  });
  it('rejects invalid calendar dates before touching the database', async () => {
    const form = new FormData();
    form.set('title', 'Verified project story');
    form.set('slug', 'verified-project-story');
    form.set('projectDate', '2026-02-31');
    form.set('challenge', 'A detailed verified challenge description from the completed work.');
    form.set('solution', 'A detailed verified solution description from the completed work.');
    const result = await saveProject(form);
    expect(result).toMatchObject({ ok: false });
    expect(mocks.mediaCount).not.toHaveBeenCalled();
  });
  it('requires useful alt text for every attached photo before project approval', async () => {
    mocks.projectFindFirst.mockResolvedValueOnce({
      slug: 'qa-project',
      body: { challenge: 'A verified challenge.', solution: 'A verified solution.' },
      clientName: null,
      clientPermissionAt: null,
      images: [{ alt: '' }],
    });
    const result = await approveProject('project-1', new Date().toISOString());
    expect(result).toMatchObject({
      ok: false,
      message: expect.stringContaining('descriptive alt text'),
    });
    expect(mocks.txProjectUpdateMany).not.toHaveBeenCalled();
  });
});
